interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string, values?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);
const LANGUAGE_KEY = 'aegis_language';

function isLanguage(value: string | null): value is Language {
  return value === 'en' || value === 'ru';
}

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (isLanguage(saved)) return saved;
    return navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
  });

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    localStorage.setItem(LANGUAGE_KEY, nextLanguage);
  };

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (text, values) => {
      let translated = language === 'ru' ? (ru as Record<string, string>)[text] || text : (en as Record<string, string>)[text] || text;
      if (values) {
        for (const [key, replacement] of Object.entries(values)) {
          translated = translated.split(`{${key}}`).join(String(replacement));
        }
      }
      return translated;
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = (): LanguageContextValue => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within a LanguageProvider');
  return context;
};
